// Port the established GL material algorithms; keep this conversion reproducible.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/app/ui/dialogs/detail/PocketCamGpuDexelPrograms.cpp'), 'utf8');
const grid = `layout(std140, binding=7) uniform Grid {
    ivec4 sizes;
    ivec4 render;
    vec4 extent;
    vec4 bounds;
    vec4 origin;
    vec4 uAxis;
    vec4 vAxis;
    vec4 wAxis;
} grid;
#define uGridSize grid.sizes.xy
#define uMaximumIntervals grid.sizes.z
#define uRenderStride grid.sizes.w
#define uRenderGridSize grid.render.xy
#define uFineCapacity uint(grid.render.z)
#define uGridMinimum grid.extent.xy
#define uResolution grid.extent.z
#define uNarrowBand (2.0 * grid.extent.z)
#define uGridMaximum grid.bounds.xy
#define uOrigin grid.origin.xyz
#define uUAxis grid.uAxis.xyz
#define uVAxis grid.vAxis.xyz
#define uWAxis grid.wAxis.xyz
`;
const motion = `layout(push_constant) uniform Motion {
    vec4 from;
    vec4 to;
    vec4 arc;
    ivec4 dispatch;
    ivec4 tool;
} motion;
layout(std430, binding=8) readonly buffer Profiles { vec2 profiles[]; };
#define uMoveFrom motion.from.xyz
#define uMoveTo motion.to.xyz
#define uMaximumRadius motion.from.w
#define uArcSweepRadians motion.to.w
#define uArcCenter motion.arc.xy
#define uArcOrientation motion.arc.z
#define uDispatchBase motion.dispatch.xy
#define uDispatchSize motion.dispatch.zw
#define uProfileCount motion.tool.y
#define uSweepKind motion.tool.z
`;
for (const [name, file] of [['computeShader', 'dexel_cut.comp'], ['surfaceShader', 'dexel_surface.comp'], ['renderVertex', 'dexel.vert'], ['renderFragment', 'dexel.frag']]) {
    let shader = source.split(`const char* ${name} = R"(`)[1].split(')";')[0];
    shader = shader.replace(/\r/g, '').split('\n').map(line => line.replace(/^ {12}/, '')).join('\n').trim();
    shader = shader.replace(/#version 430 core/, '#version 450');
    shader = shader.replace(/^uniform .*;\r?\n/gm, '');
    shader = shader.replace(/gl_InstanceID/g, 'gl_InstanceIndex').replace(/gl_VertexID/g, 'gl_VertexIndex');
    // GL's eighth storage binding is the compact coarse list; Vulkan uses 7
    // for grid uniforms and 9 for that list.
    shader = shader.replace(/binding=7\) (readonly|writeonly) buffer CoarseEntries/g, 'binding=9) $1 buffer CoarseEntries');
    if (name !== 'renderFragment') shader = shader.replace('#version 450', '#version 450\n' + grid);
    if (name === 'computeShader') {
        shader = shader.replace('#version 450', '#version 450\n' + motion);
        shader = shader.replace(/uProfile\[([^\]]+)\]/g, 'profiles[motion.tool.x + $1]');
    }
    if (name === 'renderVertex') {
        shader = shader.replace('#version 450', `#version 450
layout(push_constant) uniform Draw { mat4 mvp; mat4 scene; } draw;
layout(constant_id=0) const bool uFinePass = false;`);
        shader = shader.replace(/uModelViewProjection/g, 'draw.mvp').replace(/uSceneTransform/g, 'draw.scene');
        shader = shader.replace('out vec3 vNormal;', 'layout(location=0) out vec3 vNormal;');
    }
    if (name === 'renderFragment') {
        shader = shader.replace('in vec3 vNormal;', 'layout(location=0) in vec3 vNormal;');
        shader = shader.replace('out vec4 fragColor;', 'layout(location=0) out vec4 fragColor;\nconst vec4 uColor = vec4(102.0/255.0, 208.0/255.0, 173.0/255.0, 1.0);');
    }
    const destination = path.join(root, 'resources/shaders/cam', file);
    const output = '// Generated by tools/Generate-CamVulkanShaders.cjs; source algorithm: PocketCamGpuDexelPrograms.cpp\n' + shader + '\n';
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(destination, 'utf8').replace(/\r/g, '') !== output)
            throw new Error(`${file} is stale; rerun tools/Generate-CamVulkanShaders.cjs`);
    } else fs.writeFileSync(destination, output);
}
